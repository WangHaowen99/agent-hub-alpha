"""Generate the Go identity validator's embedded resource from the shared schema."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
doc = json.loads((root / 'schema/event-ledger.schema.json').read_text(encoding='utf-8-sig'))
identity = doc['$defs']['identity']
identity['$id'] = 'https://agent-festival.local/schema/identity/0.2.0'
body = '// Code generated by schema/embed_go.py; DO NOT EDIT.\npackage ledger\n\nconst identitySchemaJSON = `'
body += json.dumps(identity, ensure_ascii=False, sort_keys=True, indent=2) + '`\n'
(root / 'go/internal/ledger/identity_schema_generated.go').write_text(body, encoding='utf-8')
